export interface KeypadCoordinates {
    x: number;
    y: number;
}

export function getKeypadCoordinates(model: string | undefined, column: number, row: number): KeypadCoordinates | undefined {
    if (!model || !Number.isInteger(column) || !Number.isInteger(row)) return undefined;
    const aliases = ["M18", "N3", "N4Pro", "N4", "XL", "293S", "293", "L3", "K1", "N1", "M3"];
    const matched = aliases.find(alias => model.includes(alias));
    const device = matched === "L3" ? "M3" : matched;
    if (!device) return undefined;
    const mapped = keyMap[device]?.[`${column},${row}`];
    return mapped ? { x: mapped[0], y: mapped[1] } : undefined;
}
